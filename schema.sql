-- Схема
DROP SCHEMA IF EXISTS ddos_ai CASCADE;
CREATE SCHEMA ddos_ai;

-- Типы ENUM
CREATE TYPE ddos_ai.attack_type AS ENUM (
    'syn_flood', 'udp_flood', 'http_flood', 'icmp_flood',
    'dns_amplification', 'ntp_amplification', 'slowloris', 'mixed'
);
CREATE TYPE ddos_ai.model_family AS ENUM (
    'random_forest', 'xgboost', 'lstm', 'cnn', 'transformer', 'autoencoder', 'gnn'
);
CREATE TYPE ddos_ai.run_status AS ENUM ('queued', 'running', 'completed', 'failed');

-- Модели
CREATE TABLE ddos_ai.models (
    model_id      integer GENERATED BY DEFAULT AS IDENTITY,
    name          varchar(100)         NOT NULL,
    family        ddos_ai.model_family NOT NULL,
    version       varchar(20)          NOT NULL DEFAULT '1.0',
    is_production boolean              NOT NULL DEFAULT false,
    tags          text[]               NOT NULL DEFAULT '{}',
    created_at    timestamptz          NOT NULL DEFAULT now(),
    CONSTRAINT pk_models PRIMARY KEY (model_id),
    CONSTRAINT uq_models_name UNIQUE (name),
    CONSTRAINT chk_models_name CHECK (char_length(trim(name)) >= 3),
    CONSTRAINT chk_models_version CHECK (version ~ '^[0-9]+(\.[0-9]+){0,2}$')
);

-- Датасеты
CREATE TABLE ddos_ai.datasets (
    dataset_id   integer GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(100)          NOT NULL,
    source       varchar(200)          NOT NULL,
    attack_types ddos_ai.attack_type[] NOT NULL,
    records      bigint                NOT NULL,
    collected_on date                  NOT NULL,
    CONSTRAINT pk_datasets PRIMARY KEY (dataset_id),
    CONSTRAINT uq_datasets_name UNIQUE (name),
    CONSTRAINT chk_datasets_records CHECK (records > 0),
    CONSTRAINT chk_datasets_attacks CHECK (cardinality(attack_types) >= 1),
    CONSTRAINT chk_datasets_date CHECK (collected_on >= DATE '2000-01-01')
);

-- Эксперименты
CREATE TABLE ddos_ai.experiments (
    experiment_id integer GENERATED BY DEFAULT AS IDENTITY,
    title         varchar(150)        NOT NULL,
    model_id      integer             NOT NULL,
    dataset_id    integer,
    target_attack ddos_ai.attack_type NOT NULL,
    started_on    date                NOT NULL DEFAULT CURRENT_DATE,
    description   text,
    CONSTRAINT pk_experiments PRIMARY KEY (experiment_id),
    CONSTRAINT fk_experiments_model FOREIGN KEY (model_id)
        REFERENCES ddos_ai.models (model_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_experiments_dataset FOREIGN KEY (dataset_id)
        REFERENCES ddos_ai.datasets (dataset_id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT uq_experiments_title_model UNIQUE (title, model_id),
    CONSTRAINT chk_experiments_title CHECK (char_length(trim(title)) >= 3)
);

-- Запуски
CREATE TABLE ddos_ai.runs (
    run_id          integer GENERATED BY DEFAULT AS IDENTITY,
    experiment_id   integer            NOT NULL,
    run_no          smallint           NOT NULL,
    status          ddos_ai.run_status NOT NULL DEFAULT 'queued',
    started_at      timestamp          NOT NULL DEFAULT now(),
    precision_score numeric(5,4),
    recall_score    numeric(5,4),
    f1_score        numeric(5,4),
    latency_ms      real,
    epochs          smallint           NOT NULL DEFAULT 10,
    gpu_used        boolean            NOT NULL DEFAULT false,
    feature_set     text[]             NOT NULL,
    CONSTRAINT pk_runs PRIMARY KEY (run_id),
    CONSTRAINT fk_runs_experiment FOREIGN KEY (experiment_id)
        REFERENCES ddos_ai.experiments (experiment_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_runs_experiment_no UNIQUE (experiment_id, run_no),
    CONSTRAINT chk_runs_no CHECK (run_no > 0),
    CONSTRAINT chk_runs_precision CHECK (precision_score BETWEEN 0 AND 1),
    CONSTRAINT chk_runs_recall CHECK (recall_score BETWEEN 0 AND 1),
    CONSTRAINT chk_runs_f1 CHECK (f1_score BETWEEN 0 AND 1),
    CONSTRAINT chk_runs_latency CHECK (latency_ms >= 0),
    CONSTRAINT chk_runs_epochs CHECK (epochs BETWEEN 1 AND 1000),
    CONSTRAINT chk_runs_features CHECK (cardinality(feature_set) >= 1),
    CONSTRAINT chk_runs_completed CHECK (status <> 'completed' OR f1_score IS NOT NULL)
);
